def _tok(u):
    if u is None: return 0, 0
    if hasattr(u, "tokens"): return u.tokens.input_cache_miss + u.tokens.input_cache_hit, u.tokens.output
    if isinstance(u, dict): return u.get("prompt_tokens", 0), u.get("completion_tokens", 0)
    return 0, 0


class AppWorldLitellmModel(LitellmModel):
    """litellm model subclass: swap tools for AppWorld API schemas and parse arbitrary tool calls.

    Only overrides the three model-layer methods (tools in _query, the tool-name
    whitelist in _parse_actions, and the trace wrapper in query); DefaultAgent's
    control flow is completely unaware.
    """

    tool_schemas: list[dict] = []   # Set after per-task prediction (OpenAI function format)
    tool_names: set[str] = set()

    def _query(self, messages, **kwargs):
        return litellm.completion(
            model=self.config.model_name,
            messages=messages,
            tools=list(self.tool_schemas),
            **(self.config.model_kwargs | kwargs),
        )

    def _parse_actions(self, response):
        """Parse arbitrary tool calls → actions (the input format of env.execute).

        The FormatError contract matches the original parse_toolcall_actions: the
        message is user-role feedback that DefaultAgent feeds back to the model
        unchanged (retry/consecutive-error exit logic unchanged).
        """
        tool_calls = response.choices[0].message.tool_calls or []
        if not tool_calls:
            raise FormatError({
                "role": "user",
                "content": "No tool calls found in the response. Every response MUST "
                           "include at least one tool call.",
                "extra": {"interrupt_type": "FormatError"},
            })
        actions = []
        for tc in tool_calls:
            name = tc.function.name
            if name not in self.tool_names:
                raise FormatError({
                    "role": "user",
                    "content": f"Unknown tool '{name}'. Only the functions listed in "
                               "the system message are available.",
                    "extra": {"interrupt_type": "FormatError"},
                })
            try:
                arguments = json.loads(tc.function.arguments)
            except Exception:
                arguments = {"raw": tc.function.arguments}
            actions.append({"name": name, "arguments": arguments, "tool_call_id": tc.id})
        return actions

    def query(self, messages, **kwargs):
        """Trace wrapper: llm_hook records the request/response (same convention as the smolagents/autogen drivers)."""
        # freezegun-immune clock (perf_counter is frozen inside the AppWorld world → elapsed time would always be 0)
        from adapter.clock import monotonic_ms
        t0 = monotonic_ms()
        message = super().query(messages, **kwargs)
        # The hooks' message extractor reads role/content via getattr, so dicts must be wrapped in SimpleNamespace
        hook_msgs = [SimpleNamespace(role=str(m.get("role", "unk")),
                                     content=str(m.get("content") or ""))
                     for m in messages]
        actions = message.get("extra", {}).get("actions", [])
        llm_hook(MAIN_MODEL_NAME, hook_msgs, message.get("extra", {}).get("response"),
                 duration_ms=monotonic_ms() - t0,
                 tools=list(self.tool_schemas),
                 tool_calls=[{"id": a.get("tool_call_id"), "name": a["name"],
                              "arguments": json.dumps(a["arguments"])} for a in actions])
        return message


class AppWorldEnvironment:
    """AppWorld implementation of the mini-swe-agent Environment protocol (duck-typing, no inheritance needed).

    - execute(action): action = {name, arguments, tool_call_id} (produced by the model layer parsing)
      → build a code string and go through appworld_execute_tool (execution + canonical recording, same as tau2)
    - supervisor__complete_task → raise Submitted (DefaultAgent's native exit mechanism,
      same as LocalEnvironment._check_finished; world state is backed up by the checkpoint provider)
    """

    def __init__(self, world, collector):
        self.world = world
        self.collector = collector

    def execute(self, action, cwd="", *, timeout=None):
        name = str(action.get("name", ""))
        args = action.get("arguments") or {}
        if not isinstance(args, dict):
            args = {"value": args}
        if "__" in name:
            app, api = name.split("__", 1)
            code = f"print(apis.{app}.{api}(**{args!r}))"
        else:
            code = f"print(apis.{name}(**{args!r}))"
        try:
            result = appworld_execute_tool(self.world, self.collector, code)
            output = {"output": str(result), "returncode": 0, "exception_info": ""}
        except Exception as e:
            output = {"output": str(e), "returncode": -1, "exception_info": str(e)}
        if name == "supervisor__complete_task":
            raise Submitted({
                "role": "exit",
                "content": str(output["output"]),
                "extra": {"exit_status": "Submitted", "submission": str(output["output"])},
            })
        return output

    def get_template_vars(self, **kwargs):
        return {"environment": "appworld"}

    def serialize(self):
        return {"info": {"config": {
            "environment": "appworld",
            "environment_type": f"{self.__class__.__module__}.{self.__class__.__name__}",
        }}}


def _build_prompts(world):
    """Official prompt flow (same as the autogen integration): instructions rendering + demos text few-shot.

    Returns (system_text, instance_text): injected directly as template variables
    into mini-swe-agent's system_template/instance_template (the templates only
    reference variables; braces in the content are not rendered a second time).
    """
    from appworld.common.io import read_file, read_json
    from appworld.common.prompts import load_prompt_to_chat_messages
    from appworld.common.text import render_template
    from appworld.common.utils import dump_yaml

    app_descriptions = dict(world.task.app_descriptions)
    app_descriptions.pop("api_docs", None)
    app_descriptions_string = dump_yaml(app_descriptions)
    prompt_template = read_file("experiments/prompts/function_calling_agent/instructions.txt")
    header_content = render_template(
        prompt_template,
        instruction=world.task.instruction,
        main_user=world.task.supervisor,
        app_descriptions=app_descriptions_string,
        max_steps=MAX_STEPS,
    )
    header_messages = load_prompt_to_chat_messages(
        header_content, skip_system_message=False, only_header=True)
    system_text = "\n\n".join(m["content"] for m in header_messages if m["role"] == "system")

    lines = ["Below are a few example conversations:", ""]
    demo_messages = read_json("experiments/prompts/function_calling_agent/demos.json")
    for d in demo_messages:
        role = d.get("role")
        if role == "user":
            lines.append(f"User: {d.get('content', '')}")
        elif role == "assistant":
            tcs = d.get("tool_calls") or []
            if tcs:
                calls = "; ".join(
                    f"{t['function']['name']}({t['function']['arguments']})" for t in tcs)
                lines.append(f"Assistant: [tool calls: {calls}]")
            elif d.get("content"):
                lines.append(f"Assistant: {d.get('content', '')}")
        elif role == "tool":
            lines.append(f"Tool result: {str(d.get('content', ''))[:300]}")
    instance_text = "\n".join(lines) + "\n\n# Real Task Instruction\n" + world.task.instruction
    return system_text, instance_text


class _StubModel:
    """For --selftest: simulate the LLM's two steps (tool call → complete_task), zero API calls."""

    def __init__(self):
        self.calls = 0

    def query(self, messages, **kwargs):
        self.calls += 1
        if self.calls == 1:
            actions = [{"name": "spotify__play_song", "arguments": {"song_id": "1"},
                        "tool_call_id": "c1"}]
        else:
            actions = [{"name": "supervisor__complete_task", "arguments": {},
                        "tool_call_id": "c2"}]
        return {"role": "assistant", "content": "",
                "extra": {"actions": actions, "cost": 0.0, "timestamp": time.time()}}

    def format_message(self, **kwargs):
        return kwargs

    def format_observation_messages(self, message, outputs, template_vars=None):
        actions = message.get("extra", {}).get("actions", [])
        return [{"role": "tool", "content": o.get("output", ""),
                 "tool_call_id": a.get("tool_call_id")}
                for a, o in zip(actions, outputs)]

    def get_template_vars(self, **kwargs):
        return {}

    def serialize(self):
        return {}


