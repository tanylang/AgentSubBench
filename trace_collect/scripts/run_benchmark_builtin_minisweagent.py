"""
Collect traces using mini-swe-agent on AppWorld.

- Agent source: the DefaultAgent in source_code/swe_agents/mini-swe-agent/ (native control flow, zero changes)
- Tasks: AppWorld tasks (appworld_65_tasks.json or the default 13)
- Tools: real AppWorld APIs (world.task.api_docs.function_calling() → OpenAI function schema),
  pre-filtered by APIPredictor and passed to litellm as native function-calling tools
- Environment: the driver layer implements the Environment protocol (execute/get_template_vars/serialize):
  - execute(action) → appworld_execute_tool(world, collector, code) (unified execution + canonical recording)
  - supervisor__complete_task → raise Submitted (mini-swe-agent's native exit mechanism)
- Trace: llm_hook in the model query wrapper + tool recording in appworld_execute_tool
- Reference: scripts/run_benchmark_tau2_llmagent.py (the same integration approach used for tau2)

Hard guarantees (verified offline via --selftest):
1. Uses the vendored real mini-swe-agent source (asserts the load path at startup to prevent shadowing by the same-named PyPI package)
2. No changes to internal control flow: DefaultAgent's step loop, FormatError retries, Submitted exit,
   and cost/step limits are reused as-is; only LitellmModel is subclassed (_query/_parse_actions/query)
   and the Environment protocol is implemented (execute/get_template_vars/serialize)
3. No changes to prompt construction: system/instance messages are still rendered by
   DefaultAgent's own jinja2 template pipeline (the driver only supplies the
   {{ system_text }}/{{ instance_text }} variables; the official AppWorld prompt
   content is generated by its official render_template function)
"""
