def selftest() -> int:
    """Offline self-check (zero API calls): verify the real mini-swe-agent source + AppWorld wiring."""
    print(f"minisweagent source: {Path(_minisweagent_pkg.__file__).resolve()}")
    print(f"DefaultAgent from: {DefaultAgent.__module__}")

    # 1) Model layer: AppWorldLitellmModel._parse_actions parses arbitrary tool calls
    model = AppWorldLitellmModel(model_name="openai/test",
                                 model_kwargs={}, cost_tracking="ignore_errors")
    model.tool_names = {"spotify__play_song", "supervisor__complete_task"}
    fake_resp = SimpleNamespace(choices=[SimpleNamespace(
        message=SimpleNamespace(tool_calls=[
            SimpleNamespace(id="c1", function=SimpleNamespace(
                name="spotify__play_song", arguments='{"song_id": "1"}')),
        ], finish_reason="tool_calls"))])
    actions = model._parse_actions(fake_resp)
    assert actions == [{"name": "spotify__play_song",
                        "arguments": {"song_id": "1"}, "tool_call_id": "c1"}], actions
    try:
        model._parse_actions(SimpleNamespace(choices=[SimpleNamespace(
            message=SimpleNamespace(tool_calls=[
                SimpleNamespace(id="c2", function=SimpleNamespace(
                    name="bogus__api", arguments="{}")),
            ]))]))
        raise AssertionError("unknown tool did not trigger FormatError")
    except FormatError:
        pass
    print("[1/3] model layer OK (arbitrary tool-name parsing + FormatError contract)")

    # 2) Environment layer: action → world.execute(code) (recorded by appworld_execute_tool) + Submitted exit
    world = _StubWorld()
    collector = OrderedTraceCollector(agent_name="selftest", model="stub",
                                      benchmark_task_id="selftest")
    env = AppWorldEnvironment(world, collector)
    out = env.execute({"name": "spotify__play_song",
                       "arguments": {"song_id": "1"}, "tool_call_id": "c1"})
    assert out["returncode"] == 0, out
    assert world.codes == ["print(apis.spotify.play_song(**{'song_id': '1'}))"], world.codes
    try:
        env.execute({"name": "supervisor__complete_task", "arguments": {}})
        raise AssertionError("complete_task did not trigger Submitted")
    except Submitted:
        pass
    assert collector.tool_count == 2, collector.tool_count
    print("[2/3] environment layer OK (code form / canonical tool recording / Submitted exit)")

    # 3) End to end: the real DefaultAgent.run drives the stub model + AppWorldEnvironment
    env2 = AppWorldEnvironment(world, collector)
    agent = DefaultAgent(
        _StubModel(), env2,
        system_template="{{ system_text }}",
        instance_template="{{ instance_text }}",
        step_limit=10,
    )
    result = agent.run(task="t", system_text="S", instance_text="I")
    assert result.get("exit_status") == "Submitted", result
    assert world.codes[-1] == "print(apis.supervisor.complete_task(**{}))", world.codes
    # Prompt construction logic unchanged: system/instance messages are rendered by DefaultAgent's own template pipeline
    assert agent.messages[0]["role"] == "system" and agent.messages[0]["content"] == "S", agent.messages[0]
    assert agent.messages[1]["role"] == "user" and agent.messages[1]["content"] == "I", agent.messages[1]
    print(f"[3/3] DefaultAgent end to end OK (exit_status={result.get('exit_status')}, "
          f"{len(world.codes)} tool calls total: {world.codes})")
    return 0


def run_one(real_tid: str, prefix: str) -> str:
    from appworld import AppWorld
    from appworld_agents.code.common.api_predictor import APIPredictor
    from appworld_agents.code.simplified.language_model import LanguageModel

    out_path = os.path.join(OUTPUT_DIR, f"{prefix}.json")
    if os.path.exists(out_path):
        print(f"    [SKIP] already exists")
        return out_path

    collector = OrderedTraceCollector(
        agent_name="AppWorld-MiniSWEAgent", model=MAIN_MODEL_NAME, benchmark_task_id=prefix,
    )

    t0 = time.perf_counter()
    try:
        with AppWorld(task_id=real_tid, experiment_name=f"trace_miniswe_{prefix}") as world:
            collector.set_checkpoint_provider(
                make_appworld_checkpoint_provider(world, real_tid))
            # ── API prediction (with rate-limit retries; DeepSeek rate-limits easily in batch runs) ──
            lm = LanguageModel(**MODEL_CFG)
            api_predictor = APIPredictor(
                prompt_file_path="experiments/prompts/api_predictor.txt",
                demo_task_ids=["82e2fac_1"], max_predicted_apis=30, app_api_separator="__",
            )
            prompt_msgs = api_predictor.build_messages(world.task, include_cache_control=False)
            raw = None
            for _attempt in range(5):
                try:
                    raw = lm.generate(prompt_msgs)
                    break
                except Exception as e:
                    print(f"    API prediction retry {_attempt+1}/5: {type(e).__name__}")
                    time.sleep(15)
            if raw is None:
                raise RuntimeError("API prediction failed after 5 retries")
            predicted = api_predictor.predicted_output_to_apis(world.task, raw["content"])
            u = raw.pop("standardized_usage", None)
            i1, o1 = _tok(u)
            collector.log_llm(model=PREDICTOR_MODEL_NAME,
                              messages=[{"role": str(m.get("role", "unk")),
                                         "content": str(m.get("content") or "")}
                                        for m in prompt_msgs],
                              output_text="\n".join(predicted), input_tokens=i1, output_tokens=o1)

            # ── Tool schemas: predicted APIs + supervisor__complete_task (native OAI format) ──
            allowed = set(predicted)
            allowed.add("supervisor__complete_task")
            tool_schemas = generate_tools("oai", world, list(allowed), None)

            # ── mini-swe-agent (native DefaultAgent control flow) ──
            model_kwargs = {"api_base": MAIN_BASE_URL, "temperature": 0.0,
                            "seed": 100, "max_completion_tokens": 8192}
            if THINKING_MODE:
                model_kwargs["extra_body"] = THINKING_MODE
            model = AppWorldLitellmModel(
                model_name=f"openai/{MAIN_MODEL_NAME}",
                model_kwargs=model_kwargs,
                cost_tracking="ignore_errors",  # DeepSeek gateway has no price table, cost stays 0 (cost_limit never triggers)
            )
            model.tool_schemas = tool_schemas
            model.tool_names = {fn["function"]["name"] for fn in tool_schemas}
            env = AppWorldEnvironment(world, collector)
            system_text, instance_text = _build_prompts(world)
            agent = DefaultAgent(
                model, env,
                system_template="{{ system_text }}",
                instance_template="{{ instance_text }}",
                step_limit=MAX_STEPS,
            )
            llm_hook.register(collector)
            agent.run(task=world.task.instruction,
                      system_text=system_text, instance_text=instance_text)
            llm_hook.unregister()

        print(f"    done in {time.perf_counter() - t0:.0f}s")
    except Exception as e:
        import traceback
        print(f"    ERROR: {type(e).__name__}: {e}")
        traceback.print_exc()
    finally:
        llm_hook.unregister()

    collector.save(out_path, task_instruction="(loaded from AppWorld task)")
    print(f"    spans={collector._step} llm={collector.llm_count} "
          f"tools={collector.tool_count} tokens={collector.token_count:,}")
    return out_path


def main():
    import argparse
    parser = argparse.ArgumentParser(description="mini-swe-agent AppWorld trace collection")
    parser.add_argument("--selftest", action="store_true",
                        help="offline self-test (zero API calls): verify the real DefaultAgent control flow and AppWorld wiring")
    args = parser.parse_args()
    if args.selftest:
        sys.exit(selftest())

    print(f"Running {len(TASKS)} tasks with mini-swe-agent DefaultAgent\n")
    total_t0 = time.perf_counter()
    for i, (real_tid, prefix) in enumerate(TASKS, 1):
        print(f"[{i}/{len(TASKS)}] {real_tid}")
        run_one(real_tid, prefix)
    elapsed = time.perf_counter() - total_t0
    print(f"\n  Done in {elapsed:.0f}s ({elapsed/60:.1f}m)")
    print(f"  Traces: {OUTPUT_DIR}")

    # ── Required post-collection step: validator writes pass + event_type annotation ──
    from runners.finalize_traces import finalize_trace_dir
    finalize_trace_dir(OUTPUT_DIR, experiment_name="offline_eval_minisweagent")


if __name__ == "__main__":
    main()
